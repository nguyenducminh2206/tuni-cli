"""Tests for the stale-dataset warning (config newer than its generated CSV)."""
from __future__ import annotations

import os
import time
from pathlib import Path

from mi_race.train.data_prep import warn_if_stale_dataset


def _touch(path: Path, mtime: float):
    path.write_text("x")
    os.utime(path, (mtime, mtime))


def test_warns_when_config_newer_than_data(tmp_path, capsys):
    data = tmp_path / "d.csv"
    cfg_path = tmp_path / "c.json"
    _touch(data, mtime=1000)
    _touch(cfg_path, mtime=2000)          # config edited after the dataset
    cfg = {"channel": {}, "data": {"path": str(data)}}

    assert warn_if_stale_dataset(cfg_path, cfg) is True
    assert "newer than" in capsys.readouterr().out


def test_no_warning_when_data_newer(tmp_path, capsys):
    data = tmp_path / "d.csv"
    cfg_path = tmp_path / "c.json"
    _touch(cfg_path, mtime=1000)
    _touch(data, mtime=2000)              # dataset regenerated after the config
    cfg = {"channel": {}, "data": {"path": str(data)}}

    assert warn_if_stale_dataset(cfg_path, cfg) is False
    assert capsys.readouterr().out == ""


def test_no_warning_without_channel_block(tmp_path, capsys):
    # Decoder-only configs (no channel) aren't generated by generate-data.
    data = tmp_path / "d.csv"
    cfg_path = tmp_path / "c.json"
    _touch(data, mtime=1000)
    _touch(cfg_path, mtime=2000)
    cfg = {"data": {"path": str(data)}}   # no "channel"

    assert warn_if_stale_dataset(cfg_path, cfg) is False


def test_no_warning_when_data_missing(tmp_path):
    cfg_path = tmp_path / "c.json"
    cfg_path.write_text("{}")
    cfg = {"channel": {}, "data": {"path": str(tmp_path / "missing.csv")}}
    assert warn_if_stale_dataset(cfg_path, cfg) is False
